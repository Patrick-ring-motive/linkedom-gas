import {
  build
} from 'esbuild';
import {
  readFile,
  readdir,
  writeFile
} from 'node:fs/promises';
import {
  fileURLToPath
} from 'node:url';
import {
  resolve
} from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));

await build({
  absWorkingDir: root,
  entryPoints: ['src/index.js'],
  outfile: 'index.js',
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: 'es2020',
  supported: {
    'logical-assignment': false,
    'exponent-operator': false,
  },
  charset: 'utf8',
  legalComments: 'inline',
  banner: {
    js: '// Generated by npm run build. Do not edit.\n(function (nodeModule) {\nvar module = { exports: {} };',
  },
  footer: {
    js: 'if (nodeModule) nodeModule.exports = module.exports;\nelse globalThis.exports = module.exports;\n})(typeof module === "object" && module && module.exports ? module : null);',
  },
});

// Include licenses for runtime dependencies, including packages bundled upstream.
const lock = JSON.parse(await readFile(resolve(root, 'package-lock.json'), 'utf8'));
const notices = [];
for (const [path, pkg] of Object.entries(lock.packages)) {
  if (!path || pkg.dev) continue;
  const directory = resolve(root, path);
  for (const name of (await readdir(directory)).sort()) {
    if (!/^(licen[sc]e|copying|notice)(\.|$)/i.test(name)) continue;
    notices.push(`--- ${path} (${pkg.version}) / ${name} ---\n${await readFile(resolve(directory, name), 'utf8')}`);
  }
}
await writeFile(resolve(root, 'THIRD_PARTY_LICENSES.txt'), notices.join('\n\n'));
